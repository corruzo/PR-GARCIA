create or replace function public.fin_div_half_even(n numeric, d numeric)
returns bigint language plpgsql immutable strict set search_path = '' as $$
declare
  q numeric;
  r numeric;
  neg boolean;
begin
  if d = 0 then raise exception 'División entre cero'; end if;
  if d < 0 then n := -n; d := -d; end if;
  neg := n < 0;
  if neg then n := -n; end if;
  q := div(n, d);
  r := n - q * d;
  if 2 * r > d or (2 * r = d and mod(q, 2) = 1) then q := q + 1; end if;
  return (case when neg then -q else q end)::bigint;
end;
$$;
