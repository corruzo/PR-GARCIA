-- Base · Tablas que la app ya usaba antes de la cartera (proyecto nuevo).
--   * user_history: cotizaciones guardadas por usuario (App.jsx).
--   * tasa_bcv: historial de tasas que registra api/bcv.js con la service role.
-- Idempotente: no falla si las tablas ya existen.
-- ════════════════════════════════════════════════════════════════════════════


create table if not exists public.user_history (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  prestamo_data jsonb not null check (jsonb_typeof(prestamo_data) = 'object' and pg_column_size(prestamo_data) <= 65536),
  created_at timestamptz not null default now()
);
create index if not exists user_history_user_created_idx on public.user_history (user_id, created_at desc);

alter table public.user_history enable row level security;
drop policy if exists user_history_select on public.user_history;
drop policy if exists user_history_insert on public.user_history;
drop policy if exists user_history_delete on public.user_history;
create policy user_history_select on public.user_history for select to authenticated using (user_id = auth.uid());
create policy user_history_insert on public.user_history for insert to authenticated with check (user_id = auth.uid());
create policy user_history_delete on public.user_history for delete to authenticated using (user_id = auth.uid());
revoke all on public.user_history from anon;
grant select, insert, delete on public.user_history to authenticated;

create table if not exists public.tasa_bcv (
  id bigint generated by default as identity primary key,
  tasa numeric not null check (tasa > 0),
  fuente text not null,
  fecha_hora timestamptz not null default now(),
  estado text not null default 'ok'
);
create index if not exists tasa_bcv_fecha_hora_idx on public.tasa_bcv (fecha_hora desc);

-- La tasa es información pública de solo lectura; solo el servidor (service role) escribe.
alter table public.tasa_bcv enable row level security;
drop policy if exists tasa_bcv_select on public.tasa_bcv;
create policy tasa_bcv_select on public.tasa_bcv for select to anon, authenticated using (true);
revoke insert, update, delete, truncate on public.tasa_bcv from anon, authenticated;
grant select on public.tasa_bcv to anon, authenticated;
