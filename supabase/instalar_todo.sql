-- ════════════════════════════════════════════════════════════════════════════
-- Fases 3 y 4 · Pagos, abonos a capital, mora e historial de aplicación.
--
-- Reglas de negocio:
--   * Orden de aplicación por cuota (de la más antigua a la más nueva):
--     mora → interés → capital.
--   * La mora es interés simple diario sobre el capital+interés vencido y no
--     pagado, desde (vencimiento + días de gracia). Se devenga y se guarda en
--     cada pago; la vista v_cuotas_estado muestra además lo devengado hasta hoy.
--   * Los pagos se registran en orden cronológico y no se borran: se anulan
--     (solo el último pago activo de cada préstamo), con asiento de reverso.
--   * Un pago puede hacerse en USD o VES con la tasa del día; se convierte a la
--     moneda del préstamo y se guardan ambos montos.
--   * Abono a capital: primero cubre lo vencido; el resto reduce capital
--     ('reducir_plazo' = desde la última cuota; 'reducir_cuota' = proporcional).
--   * Interés sobre saldo ('saldo_insoluto'): el capital cobrado por adelantado
--     deja de generar interés desde el día del pago (prorrateo diario del
--     período en curso y descuento completo de los períodos futuros).
--   * monto_cancelacion(): cuánto salda el préstamo hoy (capital + interés
--     ganado + mora); pagado como abono, cierra el préstamo.
-- ════════════════════════════════════════════════════════════════════════════

